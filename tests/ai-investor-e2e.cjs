const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({acceptDownloads:true});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8765/ai-investor-layer.html',{waitUntil:'networkidle'});
await page.locator('#rows tr').first().waitFor();
assert.equal(await page.locator('#rows tr').count(),9,'nine project entries');
await page.locator('#search').fill('Princeton');
assert.equal(await page.locator('#rows tr').count(),2,'investor search');
await page.locator('#search').fill('');
await page.locator('#province').selectOption('Riau Islands');
assert.equal(await page.locator('#rows tr').count(),2,'province filter');
await page.locator('#province').selectOption('');
await page.locator('#hasCap').check();
assert.equal(await page.locator('#rows tr').count(),6,'MW filter');
await page.locator('#hasCap').uncheck();
await page.locator('#rows input[data-id="pdg-jc3"]').check();
assert.match(await page.locator('#comparison').innerText(),/PDG JC3/,'compare project');
assert.equal(await page.locator('#weightedRisk .panel').count(),2,'weighted risk cards');
await page.locator('#eventProject').selectOption('pdg-jc3');
assert.equal(await page.locator('#events .event').count(),1,'event filter');
const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#export').click()]);
assert.match(download.suggestedFilename(),/investor_comparison/);
assert.deepEqual(errors,[],'no frontend Javascript runtime errors');
await browser.close();
console.log('PASS: browser E2E (search, filter, comparison, risk cards, history, export)');
})().catch(e=>{console.error(e);process.exit(1)});
