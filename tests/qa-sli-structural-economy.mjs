import {test} from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {structuralEconomyEvidence} from "../js/sli-structural-economy.mjs";
import {buildBpsOfficialPanel} from "../js/sli-bps-official-panel.mjs";
const load=path=>JSON.parse(readFileSync(new URL("../"+path,import.meta.url),"utf8"));
const expenditure=load("data/sli-bps-regional-intelligence.json");
const panel=buildBpsOfficialPanel(expenditure,{balanced:true});
const register=load("data/sli-structural-industry-source-register.json");
const smelters=load("data/strategic-map-smelter-2026.json");
test("Maluku Utara structural 2022–25 comparator uses official BPS province growth and cannot invent manufacturing shares",()=>{
 const model=structuralEconomyEvidence(panel,register,smelters);
 assert.equal(model.schema,"sli-structural-economy-lens-v1");
 assert.equal(model.original_year_count,4);
 assert.deepEqual(model.yearSeries.map(r=>r.year),[2022,2023,2024,2025]);
 assert.equal(model.latest.malut_real_grdp_growth_pct,34.17);
 assert.equal(model.latest.manufacturing_real_growth_pct,62.64);
 assert.equal(model.latest.export_goods_services_growth_pct,40.13);
 assert.equal(model.latest.rank_descending,1);
 assert.ok(model.latest.province_median_real_growth_pct>0&&model.latest.province_median_real_growth_pct<15);
 assert.ok(model.latest.malut_minus_median_pp>20);
 assert.ok(model.yearSeries.every(r=>r.province_count===32));
 assert.ok(model.yearSeries.every(r=>r.rank_descending>=1&&r.rank_descending<=32));
 assert.equal(model.research_gate.historical_extension_ready,false);
 assert.equal(model.research_gate.quantitative_industry_share_ready,false);
 assert.equal(model.research_gate.panel_industry_regressors_ready,false);
 assert.match(model.research_gate.reason,/not yet been digitized/i);
 assert.match(model.synthesis.join(" "),/NOT the share of growth caused by nickel/);
 assert.match(model.methodological_limits.join(" "),/contribution\/share to annual GRDP growth/);
 assert.equal(model.facilityExamples.length,5);
 assert.ok(model.facilityExamples.every(r=>r.source.startsWith("https://")&&r.caveat.includes("not a provincially exhaustive")));
});
test("Official historical / industry source catalogue is discoverable but unverified vintages are forbidden for FE",()=>{
 assert.equal(register.publications.length,6);
 assert.equal(register.validation_policy.approved_observations,128);
 assert.equal(register.validation_policy.allow_historical_extension,false);
 assert.equal(register.validation_policy.allow_industry_controls,false);
 assert.equal(register.publications.filter(p=>p.status==="numeric_ingested_sli").length,1);
 assert.equal(register.publications.filter(p=>p.status==="publication_found_numeric_not_ingested").length,5);
 assert.ok(register.publications.every(p=>p.publisher.startsWith("BPS")&&p.url.startsWith("https://")));
 assert.equal(register.publications.find(p=>p.id==="bps_exp_2019_2023").years[0],2019);
 assert.equal(register.publications.find(p=>p.id==="bps_industry_2021_2025").years.at(-1),2025);
 assert.equal(register.case_facts.manufacturing_real_growth_pct,62.64);
 assert.match(register.case_facts.note,/not manufacturing's GRDP SHARE/);
});
test("Structural lens must fail on unverified growth, unsupported source metadata or time extension",()=>{
 const fake=JSON.parse(JSON.stringify(register));fake.validation_policy.allow_historical_extension=true;
 assert.throws(()=>structuralEconomyEvidence(panel,fake,smelters),/must not be enabled/);
 const bad=JSON.parse(JSON.stringify(register));bad.case_facts.manufacturing_real_growth_pct=null;
 assert.throws(()=>structuralEconomyEvidence(panel,bad,smelters),/Missing official/);
 const inconsistency=JSON.parse(JSON.stringify(register));inconsistency.case_facts.real_grdp_growth_pct=5;
 assert.throws(()=>structuralEconomyEvidence(panel,inconsistency,smelters),/disagrees with SLI/);
 assert.throws(()=>structuralEconomyEvidence({...panel,n:160},register,smelters),/requires audited BPS/);
});
