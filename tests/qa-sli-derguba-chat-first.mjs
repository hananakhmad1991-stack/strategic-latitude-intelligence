import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const root=new URL('../',import.meta.url),read=p=>readFileSync(new URL(p,root),'utf8');
const html=read('sli-research-ai.html'),client=read('js/sli-research-assistant.js');
const dom=new JSDOM(html,{url:'https://example.org/sli-research-ai.html'});
const d=dom.window.document;
test('public Research AI begins with a natural-language question and clear restricted-access disclosure',()=>{
 const intro=d.querySelector('#raIntro'),prompt=d.querySelector('#raPrompt'),form=d.querySelector('#raAssistantForm');
 assert.ok(intro&&prompt&&form,'intro and form should exist');
 assert.ok((intro.compareDocumentPosition(form)&dom.window.Node.DOCUMENT_POSITION_FOLLOWING)!==0,'intro comes before question');
 assert.ok(intro.textContent.includes('DERGUBA'));
 assert.ok(intro.textContent.includes('Tanyakan dengan bahasa biasa'));
 assert.match(d.querySelector('#raAccessLabel').textContent,/Pre-launch/);
 assert.match(d.querySelector('.sli-ra-public-boundary').textContent,/Owner/);
 assert.ok(d.querySelector('.sli-ra-public-preview[href="./sli-research-evidence-preview.html"]'));
 assert.ok(d.querySelector('.sli-ra-task-links a[href="./sli-expert-connect.html"]'));
 assert.ok(d.querySelector('.sli-ra-task-links a[href="./index.html#sliPortalSectors"]'));
 assert.equal(form.querySelectorAll('button[type=submit]').length,1);
 assert.equal(form.querySelector('button[type=submit]').id,'raSend');
});
test('secondary inputs are optional and collapsed, but privacy controls are preserved',()=>{
 const form=d.querySelector('#raAssistantForm'),advanced=form.querySelector('details#raAdvancedInputs');
 assert.ok(advanced&&!advanced.hasAttribute('open'));
 assert.ok(advanced.querySelector('#raChatFiles'));
 assert.ok(advanced.querySelector('#raChatUploadConsent[type=checkbox]'));
 const consent=d.querySelector('#raExternalEvidenceChoice #raExternalSearchConsent[type=checkbox]');
 assert.ok(consent&&!consent.checked,'External search must require explicit opt-in by default');
 assert.ok(d.querySelector('#raExternalEvidenceChoice #raExternalSearchRemember[type=checkbox]'),'Optional remembered consent');
 assert.ok(!advanced.contains(consent),'Source decision must remain visible beside the prompt, not buried in advanced settings');
 assert.ok(advanced.querySelector('details#raChatPreferences'));
 assert.ok(advanced.querySelector('#raChatMethod'));
 assert.ok(advanced.querySelector('#raMode'));
 assert.match(client,/external_search:usingOwner&&files.length===0&&/);
 assert.match(client,/SLIExternalEvidencePrefs/);
 assert.match(read('js/sli-external-evidence-preferences.js'),/sli-external-web-permission-v1/);
 assert.doesNotMatch(client,/localStorage\.setItem/,'Never store Owner tokens in the client app');
 assert.match(client,/initExternalWebPermission\(\)/);
 assert.match(client,/resetQuestionWebPermission\(\)/);
 assert.match(read('research-api/src/external-research.mjs'),/if\(!consent\)return/);
 assert.match(read('research-api/src/external-research.mjs'),/if\(hasAttachments\)return/);
 assert.match(client,/if\(!\$\("raChatUploadConsent"\)\.checked\)/);
 assert.match(client,/ownerConfigured\(\)/);
 assert.match(client,/getExportData/);
});
test('provenance, Owner controls, exports and research method workbench are retained',()=>{
 const owner=d.querySelector('details#raOwnerPanel');
 assert.ok(owner&&!owner.hasAttribute('open'));
 assert.ok(owner.querySelector('#raOwnerToken[type=password]'));
 const more=d.querySelector('details#raResourcesAndStory');
 assert.ok(more&&!more.hasAttribute('open'));
 assert.ok(more.querySelector('.sli-ra-derguba-brand-story'));
 assert.ok(more.querySelector('#raOpenDataLab[href="#raAdvancedLab"]'));
 const food=d.querySelector('details#raFoodInsights');
 assert.ok(food&&!food.hasAttribute('open'),'Food intelligence should be collapsed by default');
 assert.ok(food.querySelector('#raFoodImpactMount'),'Food evidence must remain available');
 assert.match(read('js/sli-food-impact-panel.mjs'),/raFoodImpactMount/,'Food module must mount in specialist disclosure');

 assert.ok(d.querySelector('details#raSourcesPanel'));
 assert.ok(d.querySelector('#raSourcesList'));
 for(const id of ['raConversation','raTemplates','raMoreExamples','raCopy','raExport','raWord','raPdf','raModelStatement','raFollowupForm'])assert.ok(d.getElementById(id),'missing '+id);
 assert.ok(html.includes('sli-analytical-workbench-ui.mjs'));
 assert.ok(html.includes('sli-report-buttons.mjs'));
 assert.ok(html.includes('sli-derguba-chat-first.css?v=20261023-external-evidence1'));
 assert.ok(!/fetch\(.*raPrompt.*onload/.test(html),'Do not auto-submit a prompt on load');
});
test('new CSS is responsive and does not disguise commercial Owner-only restriction',()=>{
 const css=read('css/sli-derguba-chat-first.css');
 assert.match(css,/@media\(max-width:650px\)/);
 assert.match(css,/\.sli-ra-advanced-inputs/);
 assert.match(css,/\.sli-ra-task-links/);
 assert.doesNotMatch(css,/\bdisplay\s*:\s*none\s*!important\s*;?\s*\/\*Owner/);
});
after(()=>dom.window.close());
