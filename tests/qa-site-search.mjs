import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const read=p=>fs.readFileSync(p,"utf8");
const index=JSON.parse(read("data/site-search-index.json"));
const html=read("index.html");
const js=read("js/site-search.js");
const css=read("css/site-search.css");
assert.equal(index.schema,"sli-search-1");
assert.equal(index.pages.length,9);
assert.ok(index.entries.length>=800,"Global index must contain real assets and provincial records");
const expected=["overview","investment","map","trade","energy","minerals","ai","policy","methodology"];
assert.deepEqual(index.pages.map(p=>p.id),expected);
assert.equal(new Set(index.entries.map(x=>x.id)).size,index.entries.length);
for(const item of index.entries){
 assert.ok(item.title.length>=2&&item.title.length<=160,"Search result title must be meaningful");
 assert.ok(expected.includes(item.page),"Invalid page for "+item.title);
 assert.ok(["dashboard","section","topic","record","indicator"].includes(item.kind),"Invalid kind");
 assert.ok(!("url" in item),"Search must not redirect users to untrusted records");
 if(item.source)assert.match(item.source,/^data\/[a-z0-9-]+\.json$/i);
}
const counts=Object.fromEntries(["dashboard","section","topic","record","indicator"].map(k=>[k,index.entries.filter(x=>x.kind===k).length]));
assert.equal(counts.dashboard,9);
assert.ok(counts.record>=650);
assert.ok(counts.indicator>=100);
assert.ok(index.entries.some(x=>x.page==="energy"&&x.layer==="spklu"&&x.province==="Jawa Barat"));
assert.ok(index.entries.some(x=>x.page==="energy"&&x.layer==="coal_reserves"&&x.province==="Kalimantan Timur"));
assert.ok(index.entries.some(x=>/Rokan/i.test(x.title)));
assert.ok(index.entries.some(x=>/Abadi Masela/i.test(x.title)));
assert.ok(index.entries.some(x=>/Lithium/i.test(x.title)));
assert.ok(index.entries.some(x=>/Forbes|Hartono/i.test(x.title)));
assert.ok(index.entries.some(x=>/SKK Migas/i.test(x.title)));
const bindings={window:{},document:{}};
vm.runInNewContext(js,bindings,{filename:"site-search.js"});
const api=bindings.window.SLISearchMath;
assert.equal(typeof bindings.window.initSLISiteSearch,"function");
assert.equal(typeof api.rank,"function");
assert.equal(api.normalize("Panás Búmí / PLTP"),"panas bumi pltp");
const result=(q,page="overview",scope="all")=>Array.from(api.rank(index.entries,q,page,scope,12),x=>x);
const spklu=result("SPKLU Jawa Barat");
assert.ok(spklu.some(x=>x.page==="energy"&&x.layer==="spklu"&&x.province==="Jawa Barat"),"Search province detail");
assert.ok(result("batubara").some(x=>x.page==="energy"||x.page==="map"),"Bahasa ↔ English alias");
assert.ok(result("nickel").some(x=>x.page==="minerals"||x.page==="map"),"Nickel data");
assert.ok(result("Rokan").some(x=>x.page==="map"||x.page==="investment"),"Project operator source");
assert.ok(result("investment","investment","page").every(x=>x.page==="investment"),"This dashboard scope only");
assert.ok(!result("SPKLU","ai","page").some(x=>x.page==="energy"),"Local filter excludes other pages");
assert.ok(result("Gini Jawa Barat").some(x=>x.path==="gini-inequality.html"&&x.province==="Jawa Barat"),"Exact Gini province deep link");
assert.ok(result("investment Jawa Barat").some(x=>x.path==="provincial-intelligence.html"&&x.province==="Jawa Barat"),"Investor dossier exact province deep link");
assert.ok(result("smelter sulawesi tengah").some(x=>x.page==="map"||x.page==="investment"),"Bilingual Indonesian province + sector queries");
assert.ok(result("BPS Gini").some(x=>x.path==="gini-inequality.html"),"Gini dashboard must be searchable");
const mini=(title,description="",keywords="")=>({title,description,keywords,page:"energy",kind:"record"});
assert.equal(api.passes(mini("Migas production"),"gas"),0,"Do not match gas inside migas");
assert.equal(api.passes(mini("Saplne tower"),"pln"),0,"Do not match arbitrary token fragments");
assert.ok(api.passes(mini("Smelters in Central Sulawesi"),"smelter sulawesi tengah")>0,"Geographic translation and plurals");
for(const item of index.entries.filter(x=>x.path))assert.ok(/^[a-z0-9-]+\\.html$/.test(item.path),"Deep link must be a local HTML path");
assert.equal(result("ZZZX1_UNLIKELY_QUERY").length,0);
const nav=html.indexOf('id="sliGlobalSearchRoot"'),content=html.indexOf('id="content"');
assert.ok(nav>0&&nav<content,"Persistent search must live in the global header, not dynamic content");
assert.match(html,/css\/site-search\.css\?v=/);
assert.match(html,/js\/site-search\.js\?v=/);
assert.match(html,/window\.initSLISiteSearch\?\.\(/);
assert.match(html,/document\.dispatchEvent\(new CustomEvent\('sli:pagechange'/);
assert.match(js,/key\.toLowerCase\(\)==="k"/);
assert.match(js,/role","combobox"/);
assert.match(js,/aria-activedescendant/);
assert.match(js,/sli:languagechange/);
assert.match(js,/document\.getElementById\(item\.anchor\)/);
assert.match(js,/fetch\(INDEX_URL/);
assert.match(css,/sli-search-popover/);
assert.match(css,/@media\(max-width:650px\)/);
assert.match(css,/sli-search-popover\[hidden\]/);
console.log("PASS: site-wide search | 9 dashboards | "+index.entries.length+" source records | bilingual keywords | scope filters | navigation anchors | accessibility | mobile styles");
