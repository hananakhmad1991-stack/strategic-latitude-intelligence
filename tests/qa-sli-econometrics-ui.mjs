test("Investor workbench DOM: panel FE actually estimates 12 entities x 6 years, year effects and cluster SE",async()=>{
 const dom=new JSDOM(read("sli-research-ai.html"),{url:"https://example.org/sli-research-ai.html",runScripts:"outside-only",pretendToBeVisual:true});
 globalThis.window=dom.window;globalThis.document=dom.window.document;
 await import("../js/sli-analytical-workbench-ui.mjs?qa-dom=2");
 const $=id=>dom.window.document.getElementById(id);
 const records=[];
 for(let i=0;i<12;i++)for(let yr=2020;yr<2026;yr++){
  const p=i*.4+(yr-2020)+(i*yr%7)*.2,q=(yr+i*3)%6;
  records.push(["P"+i,yr,p,q,11+i*4+1.9*p-.6*q+.8*(yr-2020)+Math.sin(i+yr)*.05].join(","));
 }
 const csv=["province,year,pmtb_share_pct,electricity_access_pct,real_grdp_growth_pct",...records].join("\n");
 Object.defineProperty($("raDataFile"),"files",{configurable:true,value:[{name:"synthetic_panel.csv",size:csv.length,text:async()=>csv}]});
 $("raDataFile").dispatchEvent(new dom.window.Event("change",{bubbles:true}));await tick();
 assert.equal($("raPredictor").value,"pmtb_share_pct","Default X must represent capital formation, not annual year or economic growth");
 assert.equal($("raOutcome").value,"real_grdp_growth_pct","Default Y must be growth");
 assert.equal($("raPanelEntity").value,"province","Entity selector must default to province, not electricity");
 assert.deepEqual([...$("raPanelEntity").options].map(o=>o.value),["province"],"Numeric KPI variables are not legitimate entity identifiers");
 assert.deepEqual([...$("raPanelTime").options].map(o=>o.value),["year"],"Annual time selector must not offer other numerics");

 $("raMethod").value="panel_fe";$("raMethod").dispatchEvent(new dom.window.Event("change"));
 assert.match($("raMethodInfo").textContent,/Y = real_grdp_growth_pct; X = pmtb_share_pct/);
 $("raYearFE").checked=true;
 [...$("raExtraPredictors").options].find(o=>o.value==="electricity_access_pct").selected=true;
 $("raRunMethod").click();
 assert.match($("raModelResult").textContent,/Panel Fixed Effects/);
 assert.match($("raModelResult").textContent,/12 entitas/);
 assert.match($("raModelResult").textContent,/cluster-robust/i);
 assert.match($("raModelResult").textContent,/Unduh Investor Analytical Report/);
 assert.match($("raModelResult").textContent,/Y \(variabel terikat\) = real_grdp_growth_pct; X \(prediktor\) = pmtb_share_pct/);
 assert.equal($("raModelResult").querySelector("table tr:nth-child(2) td:first-child").textContent,"pmtb_share_pct");
 assert.match($("raModelResult").textContent,/pmtb_share_pct: hubungan positif/);
 assert.match($("raModelResult").textContent,/Keterbatasan inferensi: hanya 12 klaster entitas/);
 assert.match($("raModelResult").textContent,/Uji kestabilan koefisien/);
 assert.match($("raModelResult").textContent,/Keluarkan satu entitas/);
 assert.match($("raModelResult").textContent,/Keluarkan satu tahun/);
 assert.match($("raModelResult").textContent,/Perbandingan spesifikasi efek waktu/);
 assert.ok($("raModelResult").querySelectorAll(".ra-wb-stability table").length>=3);
 assert.match($("raModelResult").textContent,/DATA SIMULASI/);
 assert.match($("raModelResult").textContent,/electricity_access_pct/);
 // A deliberately reversed specification must be explicitly identified as a different economic question.
 $("raPredictor").value="real_grdp_growth_pct";
 $("raOutcome").value="pmtb_share_pct";
 $("raPredictor").dispatchEvent(new dom.window.Event("change"));
 $("raRunMethod").click();
 assert.match($("raModelResult").textContent,/BUKAN PMTB → pertumbuhan/);
 const correct=$("raModelResult").querySelector(".ra-wb-correct-orientation");
 assert.ok(correct,"Reversed X/Y result must offer functional one-click correction");
 assert.match(correct.textContent,/Balik X\/Y dan hitung ulang/);
 correct.click();
 assert.equal($("raPredictor").value,"pmtb_share_pct");
 assert.equal($("raOutcome").value,"real_grdp_growth_pct");
 assert.equal($("raPanelEntity").value,"province");
 assert.equal($("raPanelTime").value,"year");
 assert.equal($("raYearFE").checked,true);
 assert.equal([...$("raExtraPredictors").selectedOptions][0].value,"electricity_access_pct");
 assert.match($("raModelResult").textContent,/Panel Fixed Effects/);
 assert.doesNotMatch($("raModelResult").textContent,/BUKAN PMTB → pertumbuhan/);
 assert.match($("raModelResult").textContent,/Y \(variabel terikat\) = real_grdp_growth_pct; X \(prediktor\) = pmtb_share_pct, electricity_access_pct/);
 assert.equal($("raModelResult").querySelector("table tr:nth-child(2) td:first-child").textContent,"pmtb_share_pct");
 dom.window.close();
 delete globalThis.window;delete globalThis.document;
});
