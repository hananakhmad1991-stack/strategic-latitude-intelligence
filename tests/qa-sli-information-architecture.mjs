import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,readdirSync,existsSync} from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..'),read=p=>readFileSync(path.join(root,p),'utf8');
const files=readdirSync(root).filter(p=>p.endsWith('.html')).sort();
const js=read('js/sli-navigation.js');
let modules,groups,related;
{
 const document={readyState:'loading',addEventListener(){}};
 const window={addEventListener(){}};
 const location={pathname:'/strategic-latitude-intelligence/index.html',hash:'#overview'};
 const context={document,window,location};
 vm.runInNewContext(js,context,{filename:'sli-navigation.js'});
 assert.ok(window.SLIArchitecture,'Shared navigation catalog should initialize even before DOM readiness');
 ({modules,groups,related}=window.SLIArchitecture);
}
test('all published HTML pages share common reader navigation, glossary and reliable source transport',()=>{
 assert.ok(files.length>=30,'Do not silently remove specialist pages');
 for(const name of files){
  const s=read(name);
  for(const asset of ['js/sli-navigation.js','css/sli-navigation.css','js/sli-shared-appendix.js','js/sli-live-data.js']){
   assert.equal(s.split(asset).length-1,1,name+': expected exactly one '+asset);
  }
  assert.match(s,/<\/head>/i,name+': missing head');
 }
});
test('one source of truth for overview, sector detail, guided research and methods',()=>{
 assert.ok(modules.overview&&modules.guide&&modules.glossary&&modules.freshness);
 assert.ok(modules.province&&modules.opportunity&&modules.gini&&modules.aihub);
 assert.equal(new Set(Object.keys(modules)).size,Object.keys(modules).length);
 const used=groups.flatMap(g=>g.slice(2));
 assert.equal(new Set(used).size,used.length,'Group navigation must not duplicate modules');
 for(const id of used){assert.ok(modules[id],id+' is missing from catalog')}
 for(const [id,m] of Object.entries(modules)){
  assert.ok(m[0]&&m[1]&&m[3]&&m[4],'Bilingual module guide absent: '+id);
  const [rel,fragment='']=m[2].split('#');
  assert.match(rel,/^[a-z0-9-]+\.html$/);
  assert.ok(existsSync(path.join(root,rel)),'Missing module destination: '+m[2]);
  if(fragment)assert.equal(rel,'index.html','SPA hash routes belong to main site only');
 }
 for(const [from,ids] of Object.entries(related)){assert.ok(modules[from]);for(const id of ids)assert.ok(modules[id])}
});
test('overview is a concise decision hub and detail modules have their own homes',()=>{
 const main=read('index.html'),guide=read('sli-user-guide.html');
 assert.match(main,/id="sliPulse"/);
 assert.match(main,/sli-executive-wayfinding/);
 assert.match(main,/sli-chapter-grid/);
 assert.match(main,/sli-user-guide\.html/);
 assert.match(main,/Expenditure Inequality · Gini Ratio \(BPS\)/);
 for(const section of ['workflow','catalog','tasks','controls','trust','models','help'])
  assert.ok(guide.includes('id="'+section+'"'),'Missing reader-guide chapter '+section);
 assert.ok(guide.includes('id="sliGuideCatalog"'),'Module directory must be generated by the shared catalog');
});
test('all source terms are unique, bilingual, reference-linked and self-consistent',()=>{
 const gloss=JSON.parse(read('data/sli-unified-glossary.json'));
 assert.ok(gloss.items.length>=310,'Ensure post-audit glossary additions are retained');
 const normalized=t=>t.normalize('NFKC').toLowerCase().replace(/[‐‑–—]/g,'-').replace(/\s+/g,' ').trim();
 const names=new Set(),slugs=new Set();
 for(const item of gloss.items){
  const k=normalized(item.term);
  assert.ok(!names.has(k),'Duplicate term '+item.term);names.add(k);
  assert.ok(item.slug&&!slugs.has(item.slug));slugs.add(item.slug);
  assert.ok(item.en?.trim()&&item.id?.trim(),item.term+': incomplete translation');
  assert.ok(item.source_path?.trim(),item.term+': no source lineage');
  assert.equal(item.domains.length,new Set(item.domains).size,item.term+': redundant domains');
 }
 const page=read('sli-glossary-methodology.html');
 assert.match(page,/Methodology by research task/);
 assert.match(page,/sli-user-guide\.html/);
 assert.match(page,/312 unique terms/);
});
console.log('SLI information architecture checks complete: '+files.length+' HTML pages · '+Object.keys(modules).length+' canonical navigation destinations.');
