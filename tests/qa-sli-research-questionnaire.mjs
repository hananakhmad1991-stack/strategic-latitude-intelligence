import {test} from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {ahpFromQuestionnaire,ahpFromJson,analyseAhpText,isAhpQuestion,isAhpTable,ahpResultMarkdown} from "../js/sli-research-questionnaire.mjs";
import {verifyMethodOnlyAnswer,modelRequest,validateAssistantPayload} from "../research-api/src/assistant-core.mjs";
import {parseCsv} from "../js/sli-analytical-core.mjs";
const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
const csv=read("examples/ahp-questionnaire-sample.csv");
test("Academic questionnaire AHP: auto-detect respondent CSV, three criterion rankings, per respondent CR",()=>{
 const rows=parseCsv(csv);
 assert.equal(isAhpQuestion("olah kuesioner AHP saya"),true);
 assert.equal(isAhpQuestion("tolong hitungkan bobot kriteria"),true);
 assert.equal(isAhpTable(rows),true);
 const result=ahpFromQuestionnaire(rows);
 assert.equal(result.method,"ahp_group");
 assert.equal(result.n_respondents,3);
 assert.equal(result.n_criteria,3);
 assert.equal(result.n_comparisons,9);
 assert.equal(result.group.acceptable,true);
 assert.deepEqual(result.ranking.map(r=>r.name),["Biaya","Listrik","Logistik"]);
 assert.ok(result.ranking[0].weight>0.5);
 assert.equal(result.inconsistent_respondents.length,0);
 assert.ok(result.respondents.every(x=>x.acceptable));
 assert.match(ahpResultMarkdown(result),/Bobot/);
 assert.match(ahpResultMarkdown(result),/File tidak dikirim/);
 assert.match(ahpResultMarkdown(result,"en"),/Criterion/);
 assert.deepEqual(analyseAhpText(csv,"a.csv").ranking,result.ranking);
});
test("Local AHP rejects incomplete, duplicate, invalid and misdirected comparisons; never imputes",()=>{
 const rows=parseCsv(csv);
 assert.throws(()=>ahpFromQuestionnaire(rows.slice(1)),/Incomplete AHP questionnaire/);
 assert.throws(()=>ahpFromQuestionnaire([...rows,rows[0]]),/Duplicate AHP comparison/);
 assert.throws(()=>ahpFromQuestionnaire([{...rows[0],value:"99"},...rows.slice(1)]),/Saaty score/);
 assert.throws(()=>ahpFromQuestionnaire([{...rows[0],value:"0"},...rows.slice(1)]),/Saaty score/);
 assert.throws(()=>analyseAhpText(csv,"questionnaire.pdf"),/CSV or JSON/);
 assert.throws(()=>ahpFromJson({criteria:["a","b"],pairwise:[[1,3],[3,1]]}),/reciprocal/);
});
test("JSON AHP single and rows matrix yields computed results, no fake academic claims",()=>{
 const data={criteria:["A","B","C"],pairwise:[[1,2,6],[1/2,1,3],[1/6,1/3,1]]};
 const x=ahpFromJson(data);
 assert.equal(x.n_respondents,1);
 assert.equal(x.n_criteria,3);
 assert.equal(x.group.acceptable,true);
 assert.equal(analyseAhpText(JSON.stringify(data),"quiz.json").n_respondents,1);
 assert.equal(ahpFromJson({rows:parseCsv(csv)}).n_respondents,3);
 assert.match(ahpResultMarkdown(x),/Konsistensi|konsistensi/);
});
test("General researchers get source-free conceptual methodology answer, but not fabricated SLI citations",()=>{
 const payload=validateAssistantPayload({question:"Help me design an AHP instrument for a graduate thesis",mode:"deep_research",language:"en",history:[],methodology:"auto"});
 assert.ok(payload);
 const request=modelRequest(payload,[],"test-model");
 assert.equal(request.store,false);
 assert.match(request.instructions,/general-purpose academic/);
 assert.match(request.instructions,/NO MATCHING SLI EVIDENCE/);
 assert.match(request.instructions,/without evidence|research design guidance|RESEARCH DESIGN ONLY/i);
 assert.equal(verifyMethodOnlyAnswer("This is a conceptual research design. Define the questions, criteria, respondents, validate judgments and report limitations. No empirical model has been estimated."),true);
 assert.equal(verifyMethodOnlyAnswer("Official SLI data prove this claim [1] and therefore our analysis is conclusive."),false);
 assert.match(read("research-api/src/owner-test-worker.mjs"),/verifyMethodOnlyAnswer/);
 assert.match(read("research-api/src/index.js"),/verifyMethodOnlyAnswer/);
});
