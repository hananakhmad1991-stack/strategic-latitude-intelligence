test("Private document upload supports images/PDF/Office/text without storing files in SLI",async()=>{
 assert.equal(MAX_FILES,2);
 assert.ok(LIMIT_BYTES<=600000);
 assert.equal(fileDefinition("analysis.xlsx").use,"document");
 assert.equal(fileDefinition("photo.webp").use,"image");
 assert.equal(fileDefinition("source.PDF").mime,"application/pdf");
 assert.equal(fileDefinition("malware.exe"),null);
 const pdf=bytes("report.pdf",[37,80,68,70,45,49,46,52,10,97,98,99]);
 const png=bytes("map.png",[137,80,78,71,13,10,26,10,0,0,0,0]);
 const text=bytes("notes.txt",[97,98,99]);
 recognizedFiles([pdf,png]);
 const b=await encodeAttachments([pdf,png]);
 assert.equal(b.length,2);
 const valid=validateOwnerAttachments(b);
 assert.equal(valid.length,2);
 const parts=buildOwnerFileParts(valid);
 assert.equal(parts[0].type,"input_file");
 assert.ok(parts[0].file_data.startsWith("data:application/pdf;base64,"));
 assert.equal(parts[1].type,"input_image");
 assert.ok(parts[1].image_url.startsWith("data:image/png;base64,"));
 const txt=buildOwnerFileParts(await encodeAttachments([text]));
 assert.match(txt[0].text,/UNVERIFIED USER ATTACHMENT/);
 assert.throws(()=>validateOwnerAttachments([{...b[0],mime:"image/png"}]),/invalid_attachment_type/);
 assert.throws(()=>validateOwnerAttachments([{...b[0],base64:"aGVsbG8="}]),/attachment_size_mismatch/);
 await assert.rejects(()=>encodeAttachments([bytes("fake.pdf",[0,0,0,0,0])]),/header mismatch/);
 assert.throws(()=>recognizedFiles([pdf,pdf,pdf]),/two files/);
 assert.throws(()=>recognizedFiles([{name:"too-large.pdf",size:LIMIT_BYTES+1}]),/File size/);
});
